export function icon(name, size = 18) {
  const rows = GRIDS[name];
  const w = rows[0].length, h = rows.length;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < w; x++) {
      if (row[x] !== '#') continue;
      let run = 1;
      while (row[x + run] === '#') run++;
      rects += `<rect x="${x}" y="${y}" width="${run}" height="1"/>`;
      x += run - 1;
    }
  });
  const height = Math.round(size * h / w);
  return `<svg class="icon" viewBox="0 0 ${w} ${h}" width="${size}" height="${height}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
